
"""
Comparison Engine
=================

Compares hydraulic simulation scenarios generated by WNTR.

Main capabilities:
1. Reference-based scenario comparison
2. Node and link element comparison
3. Absolute and percentage differences
4. Time-series statistics
5. Network performance indicators
6. Pearson, Spearman and Kendall correlation
7. Parameter sensitivity indicators
8. Independent metric ranking
9. Optional engineering limit assessment
10. JSON export

Input:
- Simulation_Results.json
- Scenario_Definitions.json

Output:
- Comparison_Results.json

The module does not run hydraulic simulations.
"""

import json
import math

from pathlib import Path
from datetime import datetime, timezone

import numpy as np
import pandas as pd

try:
    from scipy import stats
except ImportError:
    stats = None


class ComparisonEngineError(Exception):
    """Custom exception for Comparison Engine."""
    pass


class ComparisonEngine:

    # ==========================================
    # 1. INITIALIZATION
    # ==========================================

    def __init__(
        self,
        results_file,
        scenario_file,
        output_file,
        reference_scenario=None,
        engineering_limits=None
    ):

        self.results_file = Path(results_file)
        self.scenario_file = Path(scenario_file)
        self.output_file = Path(output_file)

        self.reference_scenario = reference_scenario

        self.engineering_limits = (
            engineering_limits or {}
        )

        self.simulation_data = None
        self.scenario_data = None

        self.results = {}

        self.scenario_definitions = {}
        self.scenario_inputs = {}

        self.dataframes = {}

        self.scenario_order = []

    # ==========================================
    # 2. LOAD INPUT FILES
    # ==========================================

    def load_data(self):
        """Load simulation results and scenario definitions."""

        for path in (
            self.results_file,
            self.scenario_file
        ):

            if not path.is_file():

                raise FileNotFoundError(
                    f"Required file not found: {path}"
                )

        with open(
            self.results_file,
            "r",
            encoding="utf-8"
        ) as file:

            self.simulation_data = json.load(file)

        with open(
            self.scenario_file,
            "r",
            encoding="utf-8"
        ) as file:

            self.scenario_data = json.load(file)

        scenarios = self.scenario_data.get(
            "Scenarios",
            []
        )

        self.scenario_definitions = {
            item["Scenario name"]: item
            for item in scenarios
        }

        self.scenario_order = list(
            self.scenario_definitions.keys()
        )

        if not self.scenario_order:

            raise ComparisonEngineError(
                "No scenarios found in Scenario_Definitions.json."
            )

        available_results = self.simulation_data.get(
            "Scenarios",
            {}
        )

        if not available_results:

            raise ComparisonEngineError(
                "No scenario results found in Simulation_Results.json."
            )

        if self.reference_scenario is None:

            self.reference_scenario = (
                self.scenario_order[0]
            )

        if self.reference_scenario not in available_results:

            raise ComparisonEngineError(
                "Reference scenario does not exist in simulation results: "
                f"{self.reference_scenario}"
            )

        if (
            available_results[self.reference_scenario].get("Status")
            != "SUCCESS"
        ):

            raise ComparisonEngineError(
                "Reference scenario was not simulated successfully."
            )

        print("\n")
        print("=" * 60)
        print("COMPARISON ENGINE - INPUT VALIDATION")
        print("=" * 60)

        print(
            "Simulation results:",
            self.results_file
        )

        print(
            "Scenario definitions:",
            self.scenario_file
        )

        print(
            "Reference scenario:",
            self.reference_scenario
        )

        print(
            "Defined scenarios:",
            len(self.scenario_order)
        )

        print(
            "Available simulation results:",
            len(available_results)
        )

        return True

    # ==========================================
    # 3. GENERAL JSON CONVERSION
    # ==========================================

    @staticmethod
    def to_json_safe(value):
        """Convert NumPy and Pandas values to JSON-safe values."""

        if value is None or value is pd.NA or value is pd.NaT:
            return None

        if isinstance(value, dict):

            return {
                str(key): ComparisonEngine.to_json_safe(val)
                for key, val in value.items()
            }

        if isinstance(value, (list, tuple)):

            return [
                ComparisonEngine.to_json_safe(item)
                for item in value
            ]

        if isinstance(value, np.ndarray):

            return ComparisonEngine.to_json_safe(
                value.tolist()
            )

        if isinstance(value, np.generic):

            return ComparisonEngine.to_json_safe(
                value.item()
            )

        if isinstance(value, (pd.Timestamp, datetime)):

            return value.isoformat()

        if isinstance(value, float):

            if not math.isfinite(value):
                return None

            return value

        if isinstance(value, (str, int, bool)):

            return value

        return str(value)

    # ==========================================
    # 4. RESTORE DATAFRAME
    # ==========================================

    def restore_dataframe(self, serialized):
        """Restore a DataFrame from Results Manager split format."""

        if not isinstance(serialized, dict):

            return None

        if serialized.get("Format") != "split":

            return None

        try:

            dataframe = pd.DataFrame(
                data=serialized["Data"],
                index=serialized["Index"],
                columns=serialized["Columns"]
            )

            dataframe = dataframe.apply(
                pd.to_numeric,
                errors="coerce"
            )

            return dataframe

        except (
            KeyError,
            TypeError,
            ValueError
        ):

            return None

    # ==========================================
    # 5. LOAD SUCCESSFUL SCENARIO DATAFRAMES
    # ==========================================

    def prepare_dataframes(self):
        """Restore node and link result DataFrames."""

        all_results = self.simulation_data.get(
            "Scenarios",
            {}
        )

        self.dataframes = {}

        for scenario_name, scenario in all_results.items():

            if scenario.get("Status") != "SUCCESS":
                continue

            self.dataframes[scenario_name] = {
                "Node": {},
                "Link": {}
            }

            for group_name, result_name in (
                ("Node", "Node_Results"),
                ("Link", "Link_Results")
            ):

                result_group = scenario.get(
                    result_name,
                    {}
                )

                for variable_name, serialized in result_group.items():

                    dataframe = self.restore_dataframe(
                        serialized
                    )

                    if dataframe is not None:

                        self.dataframes[scenario_name][
                            group_name
                        ][variable_name] = dataframe

        if self.reference_scenario not in self.dataframes:

            raise ComparisonEngineError(
                "Reference scenario data could not be restored."
            )

        print("\nDataFrame preparation completed.")

        return self.dataframes

    # ==========================================
    # 6. EXTRACT NUMERIC SCENARIO INPUTS
    # ==========================================

    def extract_scenario_inputs(self):
        """Extract numeric input parameters from scenario definitions."""

        self.scenario_inputs = {}

        for scenario_name in self.scenario_order:

            definition = self.scenario_definitions.get(
                scenario_name,
                {}
            )

            inputs = {}

            for change in definition.get("Changes", []):

                component = change.get("Component", "")
                element = change.get("Element", "")
                parameter = change.get("Parameter", "")

                key = (
                    f"{component}.{element}.{parameter}"
                )

                new_value = change.get("New SI Value")

                if isinstance(new_value, (int, float)):

                    inputs[key] = float(new_value)

                elif isinstance(new_value, list):

                    for item in new_value:

                        if not isinstance(item, dict):
                            continue

                        for sub_key, sub_value in item.items():

                            if isinstance(sub_value, (int, float)):

                                inputs[
                                    f"{key}.{sub_key}"
                                ] = float(sub_value)

            self.scenario_inputs[scenario_name] = inputs

        return self.scenario_inputs

    # ==========================================
    # 7. NUMERIC STATISTICS
    # ==========================================

    @staticmethod
    def calculate_statistics(values):
        """Calculate descriptive statistics for numeric values."""

        series = pd.to_numeric(
            pd.Series(values),
            errors="coerce"
        ).dropna()

        if series.empty:

            return {
                "Count": 0,
                "Minimum": None,
                "Maximum": None,
                "Mean": None,
                "Median": None,
                "Standard_Deviation": None,
                "Range": None
            }

        minimum = float(series.min())
        maximum = float(series.max())

        return {
            "Count": int(series.count()),
            "Minimum": minimum,
            "Maximum": maximum,
            "Mean": float(series.mean()),
            "Median": float(series.median()),
            "Standard_Deviation": (
                float(series.std(ddof=1))
                if len(series) > 1
                else None
            ),
            "Range": maximum - minimum
        }

    # ==========================================
    # 8. TIME-SERIES STATISTICS
    # ==========================================

    def calculate_time_statistics(self, dataframe):
        """Calculate statistics for each network element."""

        output = {}

        if dataframe is None or dataframe.empty:
            return output

        for element in dataframe.columns:

            series = pd.to_numeric(
                dataframe[element],
                errors="coerce"
            ).dropna()

            if series.empty:
                continue

            stats_data = self.calculate_statistics(
                series
            )

            minimum_time = series.idxmin()
            maximum_time = series.idxmax()

            stats_data["Time_of_Minimum"] = (
                self.to_json_safe(minimum_time)
            )

            stats_data["Time_of_Maximum"] = (
                self.to_json_safe(maximum_time)
            )

            output[str(element)] = stats_data

        return output

    # ==========================================
    # 9. PERCENTAGE CHANGE
    # ==========================================

    @staticmethod
    def percentage_change(reference, new_value):
        """
        Calculate percentage change relative to reference.

        Returns None if reference is zero or invalid.
        """

        try:

            reference = float(reference)
            new_value = float(new_value)

            if not (
                math.isfinite(reference)
                and math.isfinite(new_value)
            ):
                return None

            if reference == 0:
                return None

            return (
                (new_value - reference)
                / abs(reference)
            ) * 100

        except (
            TypeError,
            ValueError,
            ZeroDivisionError
        ):

            return None

    # ==========================================
    # 10. ELEMENT-LEVEL COMPARISON
    # ==========================================

    def compare_dataframes(
        self,
        reference_df,
        scenario_df
    ):
        """
        Compare two DataFrames by matching element names
        and time indexes.
        """

        output = {}

        if reference_df is None or scenario_df is None:
            return output

        common_elements = (
            reference_df.columns.intersection(
                scenario_df.columns
            )
        )

        common_times = (
            reference_df.index.intersection(
                scenario_df.index
            )
        )

        for element in common_elements:

            ref_series = pd.to_numeric(
                reference_df.loc[
                    common_times,
                    element
                ],
                errors="coerce"
            )

            new_series = pd.to_numeric(
                scenario_df.loc[
                    common_times,
                    element
                ],
                errors="coerce"
            )

            valid = (
                ref_series.notna()
                & new_series.notna()
            )

            ref_series = ref_series[valid]
            new_series = new_series[valid]

            if ref_series.empty:
                continue

            difference = new_series - ref_series

            percentage = []

            for ref_value, new_value in zip(
                ref_series,
                new_series
            ):

                percentage.append(
                    self.percentage_change(
                        ref_value,
                        new_value
                    )
                )

            output[str(element)] = {

                "Valid_Time_Steps": len(ref_series),

                "Reference_Statistics": (
                    self.calculate_statistics(ref_series)
                ),

                "Scenario_Statistics": (
                    self.calculate_statistics(new_series)
                ),

                "Difference_Statistics": (
                    self.calculate_statistics(difference)
                ),

                "Percentage_Change_Statistics": (
                    self.calculate_statistics(percentage)
                ),

                "Time_Series": {

                    "Time": self.to_json_safe(
                        ref_series.index.tolist()
                    ),

                    "Reference": self.to_json_safe(
                        ref_series.tolist()
                    ),

                    "Scenario": self.to_json_safe(
                        new_series.tolist()
                    ),

                    "Absolute_Difference": self.to_json_safe(
                        difference.tolist()
                    ),

                    "Percentage_Change": self.to_json_safe(
                        percentage
                    )
                }
            }

        return output

    # ==========================================
    # 11. SCENARIO-LEVEL COMPARISON
    # ==========================================

    def compare_all_scenarios(self):
        """Compare every successful scenario against the reference."""

        reference = self.dataframes[
            self.reference_scenario
        ]

        all_comparisons = {}

        for scenario_name, scenario_groups in self.dataframes.items():

            if scenario_name == self.reference_scenario:
                continue

            scenario_comparison = {
                "Scenario_Name": scenario_name,
                "Reference_Scenario": self.reference_scenario,
                "Node_Comparison": {},
                "Link_Comparison": {},
                "Missing_Variables": []
            }

            for group_name in ("Node", "Link"):

                ref_group = reference[group_name]
                new_group = scenario_groups[group_name]

                for variable_name, ref_df in ref_group.items():

                    new_df = new_group.get(
                        variable_name
                    )

                    if new_df is None:

                        scenario_comparison[
                            "Missing_Variables"
                        ].append(
                            f"{group_name}.{variable_name}"
                        )

                        continue

                    comparison = self.compare_dataframes(
                        ref_df,
                        new_df
                    )

                    target = (
                        "Node_Comparison"
                        if group_name == "Node"
                        else "Link_Comparison"
                    )

                    scenario_comparison[target][
                        variable_name
                    ] = comparison

            all_comparisons[scenario_name] = (
                scenario_comparison
            )

        return all_comparisons

    # ==========================================
    # 12. NETWORK PERFORMANCE INDICATORS
    # ==========================================

    def calculate_network_performance(self):
        """Calculate network-level indicators for each scenario."""

        performance = {}

        for scenario_name, groups in self.dataframes.items():

            scenario_metrics = {
                "Node": {},
                "Link": {}
            }

            for group_name in ("Node", "Link"):

                for variable_name, dataframe in (
                    groups[group_name].items()
                ):

                    values = dataframe.to_numpy(
                        dtype=float
                    ).flatten()

                    valid_values = values[
                        np.isfinite(values)
                    ]

                    if len(valid_values) == 0:
                        continue

                    scenario_metrics[group_name][
                        variable_name
                    ] = self.calculate_statistics(
                        valid_values
                    )

            # PRESSURE ASSESSMENT
            pressure_df = self.find_variable(
                groups["Node"],
                ["pressure"]
            )

            if pressure_df is not None:

                pressure_values = (
                    pressure_df.to_numpy(dtype=float)
                )

                valid = pressure_values[
                    np.isfinite(pressure_values)
                ]

                pressure_metrics = {}

                if len(valid):

                    pressure_metrics = {

                        "Minimum_Pressure": float(
                            np.min(valid)
                        ),

                        "Maximum_Pressure": float(
                            np.max(valid)
                        ),

                        "Mean_Pressure": float(
                            np.mean(valid)
                        )
                    }

                    minimum_limit = (
                        self.engineering_limits.get(
                            "Minimum_Pressure"
                        )
                    )

                    maximum_limit = (
                        self.engineering_limits.get(
                            "Maximum_Pressure"
                        )
                    )

                    if minimum_limit is not None:

                        pressure_metrics[
                            "Values_Below_Minimum_Limit"
                        ] = int(
                            np.sum(
                                valid < minimum_limit
                            )
                        )

                        pressure_metrics[
                            "Percentage_Below_Minimum_Limit"
                        ] = float(
                            np.mean(
                                valid < minimum_limit
                            ) * 100
                        )

                    if maximum_limit is not None:

                        pressure_metrics[
                            "Values_Above_Maximum_Limit"
                        ] = int(
                            np.sum(
                                valid > maximum_limit
                            )
                        )

                scenario_metrics["Pressure_Assessment"] = (
                    pressure_metrics
                )

            # VELOCITY ASSESSMENT
            velocity_df = self.find_variable(
                groups["Link"],
                ["velocity"]
            )

            if velocity_df is not None:

                velocity_values = (
                    velocity_df.to_numpy(dtype=float)
                )

                valid = velocity_values[
                    np.isfinite(velocity_values)
                ]

                velocity_metrics = {}

                if len(valid):

                    velocity_metrics = {

                        "Minimum_Velocity": float(
                            np.min(valid)
                        ),

                        "Maximum_Velocity": float(
                            np.max(valid)
                        ),

                        "Mean_Velocity": float(
                            np.mean(valid)
                        )
                    }

                    minimum_limit = (
                        self.engineering_limits.get(
                            "Minimum_Velocity"
                        )
                    )

                    maximum_limit = (
                        self.engineering_limits.get(
                            "Maximum_Velocity"
                        )
                    )

                    if minimum_limit is not None:

                        velocity_metrics[
                            "Values_Below_Minimum_Limit"
                        ] = int(
                            np.sum(
                                valid < minimum_limit
                            )
                        )

                    if maximum_limit is not None:

                        velocity_metrics[
                            "Values_Above_Maximum_Limit"
                        ] = int(
                            np.sum(
                                valid > maximum_limit
                            )
                        )

                scenario_metrics["Velocity_Assessment"] = (
                    velocity_metrics
                )

            performance[scenario_name] = scenario_metrics

        return performance

    # ==========================================
    # 13. FIND RESULT VARIABLE
    # ==========================================

    @staticmethod
    def find_variable(group, candidates):
        """Find a result variable without case sensitivity."""

        for name, dataframe in group.items():

            normalized = str(name).lower()

            if normalized in candidates:
                return dataframe

        return None

    # ==========================================
    # 14. CORRELATION TESTS
    # ==========================================

    def calculate_correlations(
        self,
        x_values,
        y_values
    ):
        """
        Calculate Pearson, Spearman and Kendall correlations.

        Correlation tests require SciPy.
        """

        if stats is None:

            return {
                "Status": "UNAVAILABLE",
                "Reason": "SciPy is not installed."
            }

        x = np.asarray(
            x_values,
            dtype=float
        )

        y = np.asarray(
            y_values,
            dtype=float
        )

        valid = (
            np.isfinite(x)
            & np.isfinite(y)
        )

        x = x[valid]
        y = y[valid]

        sample_count = len(x)

        if sample_count < 3:

            return {
                "Status": "INSUFFICIENT_DATA",
                "Sample_Count": sample_count
            }

        if (
            np.std(x) == 0
            or np.std(y) == 0
        ):

            return {
                "Status": "CONSTANT_VARIABLE",
                "Sample_Count": sample_count
            }

        pearson = stats.pearsonr(x, y)
        spearman = stats.spearmanr(x, y)
        kendall = stats.kendalltau(x, y)

        def interpret(value):

            if value is None or not np.isfinite(value):
                return "UNDEFINED"

            absolute = abs(value)

            if absolute < 0.20:
                strength = "VERY_WEAK"

            elif absolute < 0.40:
                strength = "WEAK"

            elif absolute < 0.60:
                strength = "MODERATE"

            elif absolute < 0.80:
                strength = "STRONG"

            else:
                strength = "VERY_STRONG"

            direction = (
                "POSITIVE"
                if value > 0
                else "NEGATIVE"
                if value < 0
                else "NO_DIRECTION"
            )

            return {
                "Strength": strength,
                "Direction": direction
            }

        return {

            "Status": "SUCCESS",

            "Sample_Count": sample_count,

            "Pearson": {

                "Coefficient": float(pearson.statistic),

                "P_Value": float(pearson.pvalue),

                "Interpretation": interpret(
                    pearson.statistic
                )
            },

            "Spearman": {

                "Coefficient": float(spearman.statistic),

                "P_Value": float(spearman.pvalue),

                "Interpretation": interpret(
                    spearman.statistic
                )
            },

            "Kendall": {

                "Coefficient": float(kendall.statistic),

                "P_Value": float(kendall.pvalue),

                "Interpretation": interpret(
                    kendall.statistic
                )
            },

            "Warning": (
                "Correlation does not establish causation. "
                "P-values should be interpreted cautiously "
                "for deterministic simulation scenarios."
            )
        }

    # ==========================================
    # 15. BUILD SCENARIO-LEVEL DATA
    # ==========================================

    def build_scenario_observations(self):
        """
        Build one record per successful scenario.

        Output values are scenario-level means of the
        available simulation values.
        """

        observations = {}

        for scenario_name, groups in self.dataframes.items():

            record = {}

            for input_name, input_value in (
                self.scenario_inputs.get(
                    scenario_name,
                    {}
                ).items()
            ):

                record[f"INPUT::{input_name}"] = input_value

            for group_name in ("Node", "Link"):

                for variable_name, dataframe in (
                    groups[group_name].items()
                ):

                    values = dataframe.to_numpy(
                        dtype=float
                    ).flatten()

                    valid = values[
                        np.isfinite(values)
                    ]

                    if len(valid):

                        record[
                            f"{group_name}::{variable_name}::Mean"
                        ] = float(np.mean(valid))

                        record[
                            f"{group_name}::{variable_name}::Minimum"
                        ] = float(np.min(valid))

                        record[
                            f"{group_name}::{variable_name}::Maximum"
                        ] = float(np.max(valid))

            observations[scenario_name] = record

        return observations

    # ==========================================
    # 16. CORRELATION ANALYSIS
    # ==========================================

    def run_correlation_analysis(self):
        """
        Correlate numeric scenario input parameters
        with scenario-level output indicators.
        """

        observations = self.build_scenario_observations()

        input_names = set()
        output_names = set()

        for record in observations.values():

            for key in record:

                if key.startswith("INPUT::"):
                    input_names.add(key)

                else:
                    output_names.add(key)

        correlation_results = {}

        for input_name in sorted(input_names):

            correlation_results[input_name] = {}

            for output_name in sorted(output_names):

                x = []
                y = []

                for scenario_name in observations:

                    record = observations[scenario_name]

                    x.append(
                        record.get(input_name, np.nan)
                    )

                    y.append(
                        record.get(output_name, np.nan)
                    )

                correlation_results[input_name][
                    output_name
                ] = self.calculate_correlations(
                    x,
                    y
                )

        return {

            "Method": [
                "Pearson",
                "Spearman",
                "Kendall"
            ],

            "Sample_Unit": (
                "One observation per successful scenario"
            ),

            "Scenario_Observations": observations,

            "Correlations": correlation_results
        }

    # ==========================================
    # 17. SENSITIVITY INDICATORS
    # ==========================================

    def run_sensitivity_analysis(self):
        """
        Calculate simple input-output linear sensitivity.

        Slope is output units per input unit.
        R-squared is Pearson correlation squared.
        """

        observations = self.build_scenario_observations()

        input_names = set()
        output_names = set()

        for record in observations.values():

            for key in record:

                if key.startswith("INPUT::"):
                    input_names.add(key)

                else:
                    output_names.add(key)

        sensitivity = {}

        for input_name in sorted(input_names):

            sensitivity[input_name] = {}

            for output_name in sorted(output_names):

                x = []
                y = []

                for record in observations.values():

                    x.append(
                        record.get(input_name, np.nan)
                    )

                    y.append(
                        record.get(output_name, np.nan)
                    )

                x = np.asarray(x, dtype=float)
                y = np.asarray(y, dtype=float)

                valid = (
                    np.isfinite(x)
                    & np.isfinite(y)
                )

                x = x[valid]
                y = y[valid]

                if len(x) < 2 or np.ptp(x) == 0:

                    sensitivity[input_name][output_name] = {
                        "Status": "INSUFFICIENT_VARIATION"
                    }

                    continue

                slope, intercept = np.polyfit(
                    x,
                    y,
                    1
                )

                correlation = (
                    np.corrcoef(x, y)[0, 1]
                    if np.std(y) > 0
                    else None
                )

                sensitivity[input_name][output_name] = {

                    "Status": "SUCCESS",

                    "Sample_Count": int(len(x)),

                    "Linear_Slope": float(slope),

                    "Intercept": float(intercept),

                    "Pearson_R_Squared": (
                        float(correlation ** 2)
                        if correlation is not None
                        else None
                    ),

                    "Interpretation": (
                        "Descriptive linear sensitivity; "
                        "not proof of causation."
                    )
                }

        return sensitivity

    # ==========================================
    # 18. SCENARIO RANKING
    # ==========================================

    def rank_scenarios(self):
        """
        Rank scenarios independently for each available metric.

        Direction:
        - Minimum: lower is better
        - Maximum: higher is better
        """

        observations = self.build_scenario_observations()

        metric_names = set()

        for record in observations.values():

            metric_names.update(
                key
                for key in record
                if not key.startswith("INPUT::")
            )

        rankings = {}

        for metric in sorted(metric_names):

            values = []

            for scenario_name, record in observations.items():

                value = record.get(metric)

                if value is None:
                    continue

                if not np.isfinite(value):
                    continue

                values.append(
                    (scenario_name, float(value))
                )

            if not values:
                continue

            if metric.endswith("::Minimum"):

                values.sort(
                    key=lambda item: item[1]
                )

                direction = "ASCENDING"

            else:

                values.sort(
                    key=lambda item: item[1],
                    reverse=True
                )

                direction = "DESCENDING"

            rankings[metric] = {

                "Ranking_Direction": direction,

                "Ranking": [

                    {
                        "Rank": index + 1,
                        "Scenario": name,
                        "Value": value
                    }

                    for index, (name, value) in enumerate(values)
                ]
            }

        return rankings

