    # 20. SAVE JSON
    # ==========================================

    def save_json(self):
        """Export comparison results to JSON."""

        if not self.results:

            raise ComparisonEngineError(
                "No comparison results available. "
                "Call run() first."
            )

        self.output_file.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        with open(
            self.output_file,
            "w",
            encoding="utf-8"
        ) as file:

            json.dump(
                self.results,
                file,
                ensure_ascii=False,
                indent=4,
                allow_nan=False
            )

        print("\n")
        print("=" * 60)
        print("COMPARISON RESULTS EXPORT")
        print("=" * 60)

        print("Status: SUCCESS")

        print(
            "Output file:",
            self.output_file
        )

        print(
            "File size:",
            round(
                self.output_file.stat().st_size / 1024,
                2
            ),
            "KB"
        )

